  const glyph = (font, ch) => font.g[ch] || font.g['?'] || font.g[' '];
  function measureText(text, fontName, opts){
    opts = opts || {};
    const font = FONTS[fontName] || FONTS['5x7'];
    const ls = opts.letterSpacing == null ? 1 : opts.letterSpacing;
    const lh = opts.lineSpacing == null ? 1 : opts.lineSpacing;
    const lines = String(text).split('\n');
    let w = 0;
    for(const line of lines){ const lw = line.length ? line.length*(font.w+ls) - ls : 0; if(lw > w) w = lw; }
    return { w, h: lines.length ? lines.length*(font.h+lh) - lh : 0, font, lines, ls, lh };
  }
  // → { data:Uint8Array（1＝有字）, width, height }
  function renderText(text, fontName, opts){
    const m = measureText(text, fontName, opts);
    const out = { data: new Uint8Array(Math.max(1, m.w) * Math.max(1, m.h)), width: Math.max(1, m.w), height: Math.max(1, m.h) };
    const align = (opts && opts.align) || 'left';
    m.lines.forEach((line, li) => {
      const lw = line.length ? line.length*(m.font.w+m.ls) - m.ls : 0;
      const x0 = align === 'center' ? Math.floor((m.w - lw)/2) : align === 'right' ? (m.w - lw) : 0;
      const y0 = li*(m.font.h + m.lh);
      [...line].forEach((ch, ci) => {
        const gl = glyph(m.font, ch);
        for(let y = 0; y < m.font.h; y++) for(let x = 0; x < m.font.w; x++){
          if(gl[y*m.font.w + x] !== '#') continue;
          const tx = x0 + ci*(m.font.w + m.ls) + x, ty = y0 + y;
          if(tx >= 0 && ty >= 0 && tx < out.width && ty < out.height) out.data[ty*out.width + tx] = 1;
        }
      });
    });
    return out;
  }
